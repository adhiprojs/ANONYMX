// Instead of blocking attackers, we feed them convincing fake data.
// "Our system doesn't just block unauthorized access — it generates realistic-looking
//  but 100% fake Ghost Data to mislead attackers, wasting their resources."

use rand::Rng;
use uuid::Uuid;

// ── Brute-Force / Un-fuzzing Detection ───────────────────────────────────────

/// Detects signs of attempted reverse-fuzzing in the text.
/// If triggered, returns true and the system should serve honey data.
pub fn check_and_respond(text: &str) -> bool {
    detect_unfuzz_attempt(text)
}

/// Heuristics for detecting reverse-engineering attempts on fuzzed text
fn detect_unfuzz_attempt(text: &str) -> bool {
    let suspicious_patterns = [
        // Patterns that suggest someone is trying to fill in brackets
        r"\[.*?\]\s*=\s*",          // [PERSON] = John
        r"\[.*?\]\s*:\s*[A-Z][a-z]", // [ORG]: Specific Name
        r"original\s*:\s*",         // "original: ..."
        r"(?i)real\s+name\s*:",     // "real name:"
        r"(?i)actual\s+value",      // "actual value"
        r"replace\s+\[",            // "replace ["
    ];

    for pattern in &suspicious_patterns {
        if let Ok(re) = regex::Regex::new(pattern) {
            if re.is_match(text) {
                return true;
            }
        }
    }

    // Heuristic: if the document has brackets [X] AND specific names nearby,
    // it might be a reconstruction attempt
    let bracket_re = regex::Regex::new(r"\[[A-Z\-]+\]").unwrap();
    let name_re = regex::Regex::new(r"\b[A-Z][a-z]{3,}\s+[A-Z][a-z]{3,}\b").unwrap();
    let bracket_count = bracket_re.find_iter(text).count();
    let name_count = name_re.find_iter(text).count();

    // Suspicious if someone injected real names alongside our fuzzing brackets
    bracket_count > 2 && name_count > bracket_count
}

// ── Honey Data Generator ──────────────────────────────────────────────────────

/// Generates a realistic-looking but 100% fake dataset as JSON.
/// Used both as active defense payload and for demo purposes.
pub fn generate_fake_dataset(count: u32) -> Result<String, Box<dyn std::error::Error>> {
    let mut rng = rand::thread_rng();
    let mut records = Vec::new();

    for i in 0..count.min(50) {
        records.push(serde_json::json!({
            "id": format!("HNY-{:06}", i + 1),
            "name": fake_name(&mut rng),
            "age": fake_age(&mut rng),
            "email": fake_email(&mut rng),
            "organization": fake_org(&mut rng),
            "location": fake_location(&mut rng),
            "phone": fake_phone(&mut rng),
            "salary_bracket": fake_salary_bracket(&mut rng),
            "note": "⚠ THIS RECORD IS SYNTHETIC — GENERATED BY CONTEXT-GUARD ACTIVE DEFENSE"
        }));
    }

    Ok(serde_json::to_string_pretty(&serde_json::json!({
        "type": "HONEY_DATASET",
        "generated_by": "Context-Guard Active Defense",
        "warning": "All records are entirely synthetic and non-identifiable",
        "records": records
    }))?)
}

// ── Fake Data Generators ──────────────────────────────────────────────────────

fn fake_name(rng: &mut impl Rng) -> String {
    let first = ["Arjun", "Priya", "Kavya", "Rahul", "Divya", "Kiran",
                 "Ananya", "Vikram", "Meera", "Siddharth", "Aisha", "Rohan"];
    let last = ["Kumar", "Sharma", "Patel", "Singh", "Nair", "Menon",
                "Iyer", "Reddy", "Gupta", "Verma", "Das", "Rao"];
    format!("{} {}", first[rng.gen_range(0..first.len())], last[rng.gen_range(0..last.len())])
}

fn fake_age(rng: &mut impl Rng) -> String {
    let brackets = ["20–25", "25–30", "30–35", "35–40", "40–45", "45–50"];
    brackets[rng.gen_range(0..brackets.len())].to_string()
}

fn fake_email(rng: &mut impl Rng) -> String {
    let domains = ["honeydomain.test", "fakecorp.invalid", "notreal.example",
                   "synthetic.local", "ghost.internal"];
    let id: u32 = rng.gen_range(1000..9999);
    format!("user{}@{}", id, domains[rng.gen_range(0..domains.len())])
}

fn fake_org(rng: &mut impl Rng) -> String {
    let orgs = [
        "An Engineering College in Chennai",
        "A Financial Institution in Mumbai",
        "A Healthcare Organization in Bangalore",
        "A Government Body in Delhi",
        "An IT Company in Hyderabad",
        "A Research Institute in Pune",
    ];
    orgs[rng.gen_range(0..orgs.len())].to_string()
}

fn fake_location(rng: &mut impl Rng) -> String {
    let locs = ["[Location in Tamil Nadu]", "[Location in Maharashtra]",
                "[Location in Karnataka]", "[Location in UP]", "[REGION]"];
    locs[rng.gen_range(0..locs.len())].to_string()
}

fn fake_phone(rng: &mut impl Rng) -> String {
    // Obviously fake — starts with 0000
    format!("0000-{:03}-{:04}", rng.gen_range(100..999), rng.gen_range(1000..9999))
}

fn fake_salary_bracket(rng: &mut impl Rng) -> String {
    let brackets = ["[LOWER-INCOME]", "[MID-INCOME]",
                    "[UPPER-MID]", "[HIGH-INCOME]"];
    brackets[rng.gen_range(0..brackets.len())].to_string()
}
